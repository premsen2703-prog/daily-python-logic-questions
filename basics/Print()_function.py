#print() is for displaying output to the console.
#  It can take multiple arguments,
#  which will be printed with a space in between by default. 
# You can also customize the separator and end character using the 'sep' and 'end' parameters.
print("Hello", "World")  # Output: Hello World
print("Hello", "World", sep="-")  # Output: Hello-World
print("Hello", "World", end="!")  # Output: Hello World!
print(3)
print(3.14)
print(True)
print([1, 2, 3])
print(3+4)  # Output: 7
