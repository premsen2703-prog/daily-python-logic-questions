# Escape Characters
# Escape characters are special characters used inside strings to perform specific actions.
# They usually begin with a backslash (\).

print("Example 1: New line (\\n)")
print("Hello\nWorld")

print("\nExample 2: Tab (\\t)")
print("Name\tAge\tCity")
print("Prem\t21\tJabalpur")

print("\nExample 3: Backslash (\\\\)")
print("C:\\Users\\Prem")

print("\nExample 4: Single quotation (\\')")
print('It\'s Python')

print("\nExample 5: Double quotation (\\\")")
print("He said \"Hello\"")

print("\nExample 6: Carriage return (\\r)")
print("Hello\rWorld")

print("\nExample 7: Raw strings (r\"\")")
path = r"C:\Users\Prem\Documents"
print(path)

# Raw strings are especially useful for Windows file paths and regular expressions.